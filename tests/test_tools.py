"""Tests for the receipts pipeline itself.

The tools are the reason the documents can be trusted, so they get the same
treatment as the library. These tests exercise the checker's three passes
against documents built in a temporary directory, which is the only way to
assert that it fails when it should.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import check_numbers  # noqa: E402
import render_tables  # noqa: E402


@pytest.fixture
def workspace(tmp_path: Path, monkeypatch):
    def _build(metrics: dict, anchors: dict, documents: dict[str, str], table_values=None):
        payload = {
            "metrics": metrics,
            "anchors": anchors,
            "checked_documents": list(documents),
            "table_values": table_values or [],
        }
        (tmp_path / "docs").mkdir(exist_ok=True)
        metrics_path = tmp_path / "docs" / "metrics.json"
        metrics_path.write_text(json.dumps(payload), encoding="utf-8")
        for name, text in documents.items():
            path = tmp_path / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        monkeypatch.setattr(check_numbers, "ROOT", tmp_path)
        monkeypatch.setattr(check_numbers, "METRICS_PATH", metrics_path)
        return tmp_path

    return _build


def test_a_document_quoting_the_current_value_passes(workspace, capsys):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "12 rows differ here."})
    assert check_numbers.main() == 0


def test_a_document_quoting_a_stale_value_fails(workspace, capsys):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "19 rows differ here."})
    assert check_numbers.main() == 1


def test_a_missing_figure_fails(workspace):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "nothing here."})
    assert check_numbers.main() == 1


def test_a_missing_document_fails(workspace):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {})
    path = check_numbers.METRICS_PATH
    payload = json.loads(path.read_text())
    payload["checked_documents"] = ["absent.md"]
    path.write_text(json.dumps(payload), encoding="utf-8")
    assert check_numbers.main() == 1


def test_an_anchor_matches_across_a_wrapped_line(workspace):
    """Whitespace is collapsed, or the first thing anyone learns is to skip the hook."""
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "12\nrows differ."})
    assert check_numbers.main() == 0


def test_an_anchor_matches_a_sentence_initial_capital(workspace):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "12 Rows differ."})
    assert check_numbers.main() == 0


def test_a_thousands_separated_value_matches(workspace):
    workspace({"rows": 30000}, {"rows": ["{} rows differ"]}, {"README.md": "30,000 rows differ."})
    assert check_numbers.main() == 0


def test_a_number_in_a_code_fence_is_not_treated_as_a_claim(workspace):
    workspace(
        {"rows": 12},
        {"rows": ["{} rows differ"]},
        {"README.md": "12 rows differ.\n\n```\nsrd replay --limit 99999\n```\n"},
    )
    assert check_numbers.main() == 0


def test_a_number_in_an_inline_code_span_is_not_treated_as_a_claim(workspace):
    workspace(
        {"rows": 12},
        {"rows": ["{} rows differ"]},
        {"README.md": "12 rows differ, unlike `4321`."},
    )
    assert check_numbers.main() == 0


def test_an_unguarded_number_in_the_readme_fails(workspace):
    workspace({"rows": 12}, {"rows": ["{} rows differ"]}, {"README.md": "12 rows differ, and 77 others."})
    assert check_numbers.main() == 1


def test_a_table_value_is_recognised_by_the_backward_pass(workspace):
    workspace(
        {"rows": 12},
        {"rows": ["{} rows differ"]},
        {"README.md": "12 rows differ, and 77 others."},
        table_values=[77],
    )
    assert check_numbers.main() == 0


def test_a_stale_readme_fails_even_when_another_document_is_correct(workspace):
    """The hole the per-document pass was added to close."""
    workspace(
        {"rows": 12},
        {"rows": ["{} rows differ"]},
        {"README.md": "19 rows differ.", "docs/other.md": "12 rows differ."},
    )
    assert check_numbers.main() == 1


def test_the_shipped_documents_pass():
    assert check_numbers.main() == 0


def test_every_generated_table_names_its_source():
    for builder in (
        render_tables.arms_table,
        render_tables.lateness_table,
        render_tables.jitter_table,
        render_tables.sessions_table,
    ):
        block, _ = builder()
        assert "generated by tools/render_tables.py from" in block


def test_every_generated_table_is_closed():
    for name, builder in (
        ("arms", render_tables.arms_table),
        ("lateness", render_tables.lateness_table),
        ("jitter", render_tables.jitter_table),
        ("sessions", render_tables.sessions_table),
    ):
        block, _ = builder()
        assert block.rstrip().endswith(f"<!-- /table:{name} -->")


def test_the_readme_holds_every_generated_block():
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    for name in ("arms", "lateness", "jitter", "sessions"):
        assert f"<!-- table:{name}" in text and f"<!-- /table:{name} -->" in text


def test_regenerating_the_tables_does_not_change_the_readme():
    """The drift check CI runs, run here too so a laptop catches it first."""
    before = (ROOT / "README.md").read_text(encoding="utf-8")
    assert render_tables.main() == 0
    assert (ROOT / "README.md").read_text(encoding="utf-8") == before


def test_every_table_value_is_published_for_the_backward_pass():
    assert len(render_tables.table_values()) > 40
