def test_a_stale_readme_fails_even_when_another_document_is_correct(workspace):
    """The hole the per-document pass was added to close."""
    workspace(
        {"rows": 12},
        {"rows": ["{} rows differ"]},
        {"README.md": "19 rows differ.", "docs/other.md": "12 rows differ."},
    )
    assert check_numbers.main() == 1


