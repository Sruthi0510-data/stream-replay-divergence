"""Write the README's data tables from the experiment JSON, between committed markers.

Hand-typed table cells are the largest hole in a receipts mechanism. An anchor phrase guards a
figure quoted in a sentence; a table of thirty numbers is thirty figures nobody anchored, and
the first one to go stale goes stale silently.

So the tables are generated. Each block in the README is delimited by a marker comment, this
tool rewrites the rows between them from `docs/experiments/*.json`, and CI regenerates and
fails if the committed README differs. The numbers in those rows are then exactly the numbers
the experiments produced, and the same values are published in `docs/metrics.json` under
`table_values` so the backward check in check_numbers.py recognises them.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
EXPERIMENTS = ROOT / "docs" / "experiments"

def _block(name: str, body: str, source: str) -> str:
    return (
        f"<!-- table:{name} generated by tools/render_tables.py from {source} -->\n"
        f"{body}\n"
        f"<!-- /table:{name} -->"
    )


def arms_table() -> tuple[str, list[Any]]:
    """Where the rows that differ went, by mechanism."""
    payload = json.loads((EXPERIMENTS / "exp01.json").read_text())
    rows = [
        ("identical in both", payload["stable_rows"], "nothing to do"),
        ("changed by dropped records", payload["rows_changed_by_drops"], "allowed lateness"),
        ("changed by tie ordering", payload["rows_changed_by_ties"], "the query's last-value column"),
        ("present only in the replay", payload["rows_only_in_replay"], "allowed lateness"),
        ("present only in the original", payload["rows_only_in_original"], "nothing to do"),
    ]
    values: list[Any] = []
    lines = ["| rows | count | owner |", "| --- | --- | --- |"]
    for label, count, owner in rows:
        values.append(count)
        lines.append(f"| {label} | {count} | {owner} |")
    return _block("arms", "\n".join(lines), "exp01.json"), values


def lateness_table() -> tuple[str, list[Any]]:
    """What widening the allowed lateness buys, and what it cannot buy."""
    payload = json.loads((EXPERIMENTS / "exp03.json").read_text())
    values: list[Any] = []
    lines = [
        "| allowed lateness | records the original dropped | replay-stable rows | "
        "rows still differing | of those, tie ordering |",
        "| --- | --- | --- | --- | --- |",
    ]
    for record in payload["by_lateness"]:
        seconds = record["allowed_lateness_ms"] // 1_000
        drop = f"{100 * record['original_drop_rate']:.1f}"
        stable = f"{100 * record['replay_stable_share']:.1f}"
        values.extend([seconds, drop, stable, record["diverged_rows"], record["rows_changed_by_ties"]])
        lines.append(
            f"| {seconds} s | {drop}% | {stable}% | {record['diverged_rows']} | "
            f"{record['rows_changed_by_ties']} |"
        )
    return _block("lateness", "\n".join(lines), "exp03.json"), values


def jitter_table() -> tuple[str, list[Any]]:
    """Where the result stops being robust."""
    payload = json.loads((EXPERIMENTS / "exp03.json").read_text())
    values: list[Any] = []
    lines = [
        "| delivery spread | records the original dropped | replay-stable rows |",
        "| --- | --- | --- |",
    ]
    for record in payload["by_jitter"]:
        seconds = record["jitter_ms"] // 1_000
        drop = f"{100 * record['original_drop_rate']:.1f}"
        stable = f"{100 * record['replay_stable_share']:.1f}"
        values.extend([seconds, drop, stable])
        lines.append(f"| up to {seconds} s | {drop}% | {stable}% |")
    return _block("jitter", "\n".join(lines), "exp03.json"), values


def sessions_table() -> tuple[str, list[Any]]:
    """Every replay setting tried, and how many sessions each recovered."""
    payload = json.loads((EXPERIMENTS / "exp05.json").read_text())
    durations = sorted({row["per_batch_ms"] for row in payload["grid"]})
    sizes = sorted({row["batch_records"] for row in payload["grid"]})
    lookup = {(row["batch_records"], row["per_batch_ms"]): row["sessions"] for row in payload["grid"]}
    values: list[Any] = list(durations)
    header = "| records per batch | " + " | ".join(f"{d} ms per batch" for d in durations) + " |"
    lines = [header, "| --- " * (len(durations) + 1) + "|"]
    for size in sizes:
        values.append(size)
        cells = []
        for duration in durations:
            sessions = lookup[(size, duration)]
            values.append(sessions)
            cells.append(str(sessions))
        lines.append(f"| {size:,} | " + " | ".join(cells) + " |")
    return _block("sessions", "\n".join(lines), "exp05.json"), values


def table_values() -> list[Any]:
    """Every number the generated tables contain, for the backward check to recognise."""
    values: list[Any] = []
    for builder in (arms_table, lateness_table, jitter_table, sessions_table):
        _, produced = builder()
        values.extend(produced)
    return values


def main() -> int:
    text = README.read_text(encoding="utf-8")
    replaced = 0
    for name, builder in (
        ("arms", arms_table),
        ("lateness", lateness_table),
        ("jitter", jitter_table),
        ("sessions", sessions_table),
    ):
        block, _ = builder()
        pattern = re.compile(
            rf"<!-- table:{name}.*?-->.*?<!-- /table:{name} -->", re.DOTALL
        )
        if not pattern.search(text):
            print(f"no marker block for {name!r} in README.md")
            return 1
        text = pattern.sub(lambda _match, block=block: block, text)
        replaced += 1
    README.write_text(text, encoding="utf-8")
    print(f"rewrote {replaced} generated table block(s) in README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
